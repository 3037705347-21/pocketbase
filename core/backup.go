package core

import (
	"context"
	"fmt"
	"log/slog"
	"sort"
	"time"

	"github.com/pocketbase/pocketbase/tools/inflector"
)

const (
	StoreKeyActiveBackup = "@activeBackup"
)

// generateBackupName generates a new backup name based on the app name and current date.
func generateBackupName(app App, prefix string) string {
	appName := inflector.Snakecase(app.Settings().Meta.AppName)
	if len(appName) > 50 {
		appName = appName[:50]
	}

	return fmt.Sprintf(
		"%s%s_%s.zip",
		prefix,
		appName,
		time.Now().UTC().Format("20060102150405"),
	)
}

// registerAutobackupHooks registers the autobackup app serve hooks.
func (app *BaseApp) registerAutobackupHooks() {
	const jobId = "__pbAutoBackup__"

	loadJob := func() {
		rawSchedule := app.Settings().Backups.Cron
		if rawSchedule == "" {
			app.Cron().Remove(jobId)
			return
		}

		app.Cron().Add(jobId, rawSchedule, func() {
			const autoPrefix = "@auto_pb_backup_"

			name := generateBackupName(app, autoPrefix)

			if err := app.CreateBackup(context.Background(), name); err != nil {
				app.Logger().Error(
					"[Backup cron] Failed to create backup",
					slog.String("name", name),
					slog.String("error", err.Error()),
				)

				alertError := sendSystemAlertToAllSuperusers(
					app,
					"Autobackup failure",
					"Failed to create/upload automated backup. Raw error:\n"+err.Error(),
				)
				if alertError != nil {
					app.Logger().Warn(
						"[Backup cron] Failed to send backup error alerts",
						slog.String("name", name),
						slog.String("error", alertError.Error()),
					)
				}
			}

			// verify all backup candidates before applying the retention quota
			// so that corrupt/incomplete backups don't consume keep slots;
			// the results are persisted and reused on subsequent runs
			report, reconcileErr := app.ReconcileBackups(context.Background())
			if reconcileErr != nil {
				app.Logger().Error(
					"[Backup cron] Failed to complete backup integrity reconciliation",
					slog.String("error", reconcileErr.Error()),
				)
			}

			maxKeep := app.Settings().Backups.CronMaxKeep

			if maxKeep == 0 {
				return // no explicit limit
			}

			if reconcileErr != nil {
				// don't prune without up-to-date verification results
				return
			}

			if err := app.pruneAutoBackups(autoPrefix, maxKeep, report); err != nil {
				app.Logger().Error(
					"[Backup cron] Failed to apply the autogenerated backups retention limit",
					slog.String("error", err.Error()),
				)
			}
		})
	}

	app.OnBootstrap().BindFunc(func(e *BootstrapEvent) error {
		if err := e.Next(); err != nil {
			return err
		}

		loadJob()

		return nil
	})

	app.OnSettingsReload().BindFunc(func(e *SettingsReloadEvent) error {
		if err := e.Next(); err != nil {
			return err
		}

		loadJob()

		return nil
	})
}

// pruneAutoBackups applies the retention quota over the autogenerated
// (prefix-matching) backups using the persisted verification results.
//
// Only backups marked as [BackupVerificationValid] are counted toward the
// maxKeep quota and are eligible for automatic deletion.
// Corrupt/incomplete and not-yet-verified backups are preserved and only
// reported via logs - they are never automatically removed.
func (app *BaseApp) pruneAutoBackups(prefix string, maxKeep int, report *BackupVerificationReport) error {
	fsys, err := app.NewBackupsFilesystem()
	if err != nil {
		return err
	}
	defer fsys.Close()

	files, err := fsys.List(prefix)
	if err != nil {
		return err
	}

	verified := make([]string, 0, len(files))

	for _, f := range files {
		if !isBackupVerificationCandidate(f.Key) {
			continue
		}

		entry, ok := report.Find(f.Key)
		if !ok {
			// unverified backups are conservatively kept to avoid deleting
			// a potentially good backup
			app.Logger().Warn(
				"[Backup cron] Skipping not verified autogenerated backup during retention pruning",
				slog.String("key", f.Key),
			)
			continue
		}

		if entry.Status == BackupVerificationInvalid {
			// corrupt backups are kept and reported separately (see ReconcileBackups)
			app.Logger().Warn(
				"[Backup cron] Keeping corrupt autogenerated backup outside of the retention quota",
				slog.String("key", f.Key),
				slog.String("error", entry.Error),
			)
			continue
		}

		verified = append(verified, f.Key)
	}

	if maxKeep >= len(verified) {
		return nil // nothing to remove
	}

	// sort verified backups by modification time desc (newest first),
	// looking up the list attributes to avoid additional storage requests
	modTimes := make(map[string]time.Time, len(files))
	for _, f := range files {
		modTimes[f.Key] = f.ModTime
	}

	sort.Slice(verified, func(i, j int) bool {
		return modTimes[verified[i]].After(modTimes[verified[j]])
	})

	// keep only the most recent maxKeep verified backup files
	toRemove := verified[maxKeep:]

	for _, key := range toRemove {
		if err := fsys.Delete(key); err != nil {
			app.Logger().Error(
				"[Backup cron] Failed to remove old autogenerated backup",
				slog.String("key", key),
				slog.String("error", err.Error()),
			)
		}
	}

	return nil
}
